import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mockAccounts } from '../support/account-api'
import { mockApi } from '../support/mock-api'

test('visitor introduction is honest, assistant remains independent and direct URLs work', async ({ page }) => {
  const account = await mockAccounts(page)
  await mockApi(page)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Tableaux de bord et collaboration' })).toBeVisible()
  await expect(page.getByText(/Les tableaux de bord interactifs et le partage en lecture seule sont disponibles avec un compte/)).toBeVisible()
  await expect(page.getByText(/Les administrateurs disposent d’un espace de supervision/)).toBeVisible()
  await page.getByRole('link', { name: 'Consulter l’assistant pharmacie' }).click()
  await expect(page.getByRole('textbox', { name: 'Votre question' })).toBeVisible()
  const count = account.calls.length
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Votre question' })).toBeVisible()
  expect(account.calls).toHaveLength(count)
  await page.getByRole('link', { name: 'Mon espace' }).click()
  await expect(page).toHaveURL(/\/connexion$/)
  await page.goto('/page-absente')
  await expect(page.getByRole('heading', { name: 'Page introuvable' })).toBeVisible()
})
test('registration, profile saving, refresh, logout and route guards', async ({ page }, info) => {
  test.slow() // Complete navigation workflow plus accessibility scan.
  await mockAccounts(page)
  await page.goto('/inscription')
  await page.getByLabel('Nom affiché').fill('Camille')
  await page.getByLabel('Adresse e-mail').fill('camille@example.test')
  await page.getByLabel('Mot de passe', { exact: true }).fill('a-long-test-password')
  await page.getByRole('button', { name: 'Créer mon compte' }).click()
  await expect(page).toHaveURL(/\/espace$/)
  await expect(page.getByRole('heading', { name: 'Bonjour, Camille' })).toBeVisible()
  await page.getByRole('link', { name: 'Gérer mon profil' }).click()
  await page.getByLabel('Nom affiché').fill('Camille Nouveau')
  await page.getByRole('button', { name: 'Enregistrer le profil' }).click()
  await expect(page.getByRole('status')).toHaveText('Profil enregistré.')
  await page.reload()
  await expect(page.getByLabel('Nom affiché')).toHaveValue('Camille Nouveau')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.screenshot({ path: info.outputPath('profile-desktop.png'), fullPage: true })
  await page.goto('/administration')
  await expect(page.getByRole('heading', { name: 'Accès non autorisé' })).toBeVisible()
  await page.getByRole('button', { name: 'Se déconnecter' }).click()
  await expect(page).toHaveURL(/\/connexion$/)
  await page.goto('/profil')
  await expect(page).toHaveURL(/\/connexion$/)
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([])
})
