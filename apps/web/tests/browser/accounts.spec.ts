test('protected analytics deep link retains its explicit dataset/version through login', async ({ page }) => {
  await mockAccounts(page)
  const target='/analyses/nouvelle?dataset=776a5195-8bb7-4a9a-80ad-33592d46e997&version=ae125d65-a056-4be0-9341-411e6a958721'
  await page.goto(target)
  await expect(page).toHaveURL(/\/connexion$/)
  await page.getByLabel('Adresse e-mail').fill('analyst@example.test')
  await page.getByLabel('Mot de passe', {exact:true}).fill('login-deep-link-password')
  await page.getByRole('button', {name:'Se connecter',exact:true}).click()
  await expect(page).toHaveURL(new RegExp(target.replace(/[?]/g,'\\?')+'$'))
  await expect(page.getByRole('heading',{name:'Créer une analyse',exact:true})).toBeVisible()
})
